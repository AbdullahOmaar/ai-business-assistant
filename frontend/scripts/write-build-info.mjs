import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageInfo = JSON.parse(readFileSync(resolve(frontendRoot, 'package.json'), 'utf8'));
let commit = process.env.VERCEL_GIT_COMMIT_SHA || process.env.GITHUB_SHA || '';
if (!commit) {
  try {
    commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: frontendRoot, encoding: 'utf8' }).trim();
  } catch {
    commit = 'unknown';
  }
}

const buildInfo = {
  version: packageInfo.version,
  commit: commit.slice(0, 12) || 'unknown',
};
const output = `// Generated by scripts/write-build-info.mjs; do not edit by hand.\nexport const APP_BUILD_INFO = ${JSON.stringify(buildInfo)} as const;\n`;
writeFileSync(resolve(frontendRoot, 'src/app/build-info.ts'), output, 'utf8');

// Make every production build produce a new service-worker script. Otherwise a
// byte-identical sw.js can leave an installed PWA serving a cached old app shell.
const serviceWorkerPath = resolve(frontendRoot, 'public/sw.js');
const serviceWorker = readFileSync(serviceWorkerPath, 'utf8');
const cacheName = `aba-shell-v${buildInfo.version}-${buildInfo.commit}`;
if (!/const CACHE_NAME = '[^']+';/.test(serviceWorker)) {
  throw new Error('Could not find the service-worker cache name declaration.');
}
writeFileSync(
  serviceWorkerPath,
  serviceWorker.replace(/const CACHE_NAME = '[^']+';/, `const CACHE_NAME = '${cacheName}';`),
  'utf8',
);
console.log(`UI build metadata: v${buildInfo.version} (${buildInfo.commit})`);
console.log(`Service worker cache: ${cacheName}`);
